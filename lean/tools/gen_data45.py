#!/usr/bin/env python3
"""gen_data45.py TAILS.json CERT_V3.json OUT.lean: writes the Lean data module (parameters, T_up, R0tail, mu) for the
45a certificate from the frozen bundle (exact rationals as in the files)."""
import json, sys
from fractions import Fraction as F
tails = json.load(open(sys.argv[1])); cert = json.load(open(sys.argv[2]))
par = cert["params"]
assert tails["ELL"] == par["ELL"] and tails["PER"] == cert["PER"] == 120
mus = {F(v) for k, v in cert["duals"] if k[0] == "bud"}
assert len(mus) == 1 and len(cert["duals"]) == 120, "uniform multiplier expected"
mu = mus.pop()
def q(x):
    x = F(x)
    return f"(({x.numerator} : Int) : Rat) / ({x.denominator} : Rat)"
T = [F(t) for t in tails["T_up"]]
lines = ["/-! Generated by tools/gen_data45.py from tails_p120b_v5_c073e0de.json and cert_p120b_v3_6fd62e90.json. -/",
         "", "namespace R45.D45", "",
         "def ellPO : List (Nat × Nat) := [(3, 2), (5, 4), (7, 3), (11, 10), (13, 12), (17, 8), (31, 5), (41, 20), (241, 24)]",
         f"def C0up : Rat := {q(par['C0_up'])}",
         f"def log2lo : Rat := {q(par['log2_low'])}",
         f"def log2hi : Rat := {q(par['log2_up'])}",
         f"def R0up : Rat := {q(par['R0_up'])}",
         f"def C1v3 : Rat := {q(par['C1'])}",
         f"def muV3 : Rat := {q(mu)}",
         f"def R0tail : Rat := {q(tails['R0tail'])}",
         "def Tup : List Rat := ["] + [f"  {q(t)}," for t in T[:-1]] + [f"  {q(T[-1])}]", "", "end R45.D45", ""]
open(sys.argv[3], "w").write("\n".join(lines))
print("mu", float(mu), "R0tail", float(F(tails["R0tail"])))
