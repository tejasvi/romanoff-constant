"""Write RCert/M3/Data.lean from the Pratt/prime-list JSON (gen_pratt.py output).

usage: gen_data_lean.py PRATT.json OUT.lean [FTHRESH]
Groups: gA = non-ell primes of order <= 300 (by order), gE = ell primes (by order), gB = class-B groups (order 301..1200),
flagged exact iff sum_q ceil(2^64/(q-2)) >= FTHRESH * 2^64 (default 1e-12).
"""
import json, sys, hashlib
SC = 1 << 64
ELL = [3, 5, 7, 11, 13, 17, 31, 41, 241]
def fac(n):
    out, d = [], 2
    while d * d <= n:
        if n % d == 0:
            e = 0
            while n % d == 0: n //= d; e += 1
            out.append((d, e))
        d += 1
    if n > 1: out.append((n, 1))
    return out
def groups(lst):
    g = {}
    for p, t in lst: g.setdefault(t, []).append(p)
    return [(t, sorted(g[t])) for t in sorted(g)]
def fUp(p): return (SC + p - 3) // (p - 2)
def grp(t, ps):
    tf = ", ".join(f"({r}, {e})" for r, e in fac(t))
    return f"⟨{t}, [{tf}], [{', '.join(map(str, ps))}]⟩"
src = sys.argv[1]; out = sys.argv[2]; FT = float(sys.argv[3]) if len(sys.argv) > 3 else 1e-12
d = json.load(open(src))
A = [(p, t) for p, t in d["A"] if p not in ELL]; E = [(p, t) for p, t in d["A"] if p in ELL]
gA, gE, gB = groups(A), groups(E), groups(d["B"])
recs = d["recs"]
sha = hashlib.sha256(open(src, "rb").read()).hexdigest()
L = [f"import RCert.M3.Check", "", f"/-! Generated by M3/tools/gen_data_lean.py from {src.split('/')[-1]} (sha256 {sha[:16]}), "
     f"FTHRESH = {FT}. -/", "", "namespace R45.M3.D", "", "open R45.M3", ""]
CH = 250
names = []
for i in range(0, len(recs), CH):
    nm = f"recs{i // CH}"; names.append(nm)
    body = ",\n  ".join(f"⟨{n}, {a}, [{', '.join(f'({q}, {e})' for q, e in fl)}]⟩" for n, a, fl in recs[i:i + CH])
    L += [f"def {nm} : List PRec := [\n  {body}]", ""]
L += [f"def recs : List PRec := {' ++ '.join(names)}", ""]
def chunked(name, items, typ):
    nms = []
    for i in range(0, len(items), 60):
        nm = f"{name}{i // 60}"; nms.append(nm)
        L.extend([f"def {nm} : List {typ} := [\n  " + ",\n  ".join(items[i:i + 60]) + "]", ""])
    L.extend([f"def {name} : List {typ} := {' ++ '.join(nms)}", ""])
chunked("gA", [grp(t, ps) for t, ps in gA], "Grp")
chunked("gE", [grp(t, ps) for t, ps in gE], "Grp")
nex = 0; itemsB = []
for t, ps in gB:
    ex = sum(fUp(q) for q in ps) >= FT * SC; nex += ex
    itemsB.append(f"({grp(t, ps)}, {'true' if ex else 'false'})")
chunked("gB", itemsB, "(Grp × Bool)")
L += ["def data : Data := ⟨recs, gA, gE, gB⟩", "", "end R45.M3.D", ""]
open(out, "w").write("\n".join(L))
print(f"recs {len(recs)}, gA {len(gA)} groups / {len(A)} primes, gE {len(gE)}, gB {len(gB)} groups / {len(d['B'])} primes, "
      f"exact {nex}; wrote {out}")
