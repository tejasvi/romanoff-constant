"""Generate the K-version literal modules and kernel shards for M3 v2 (Romanoff/M3/K/*.lean).

usage: gen_kfiles.py PRATT.json KPLAN.json OUTDIR [BCHUNK]
Literals (noncomputable defs, namespace R45.M3.K): Tab<k> (DP checkpoints, with drop<k>), TabR, Sub<h> (subtables of
Tab289 by gcd(L, 120) = h), Vals (sA sB r0a acc1 subsLit), BDs (class-B data in chunks, bsLit).
Shards (one theorem each, `decide +kernel`): KDP<j>, KR, KSub<h>, KVsA, KVsB, KVr0a, KVacc1, KB<j>, KF, KC*.
Writes OUTDIR/jobs.txt (name est_seconds) and OUTDIR/plan.json (what the glue needs)."""
import json, sys, os, math
sys.set_int_max_str_digits(0)
os.environ.setdefault("KAPPA", "16384")
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import m3ref
from m3ref import groups, step, eLo, eUp, fUp, fLo, ELL, SC, LMAX
DIV = [1, 2, 3, 4, 5, 6, 8, 10, 12, 15, 20, 24, 30, 40, 60, 120]
CH = 64; SUB = 256
HDR = "set_option maxHeartbeats 0\nset_option maxRecDepth 100000\n"
def pack(ents):
    out = []
    for i in range(0, len(ents), CH):
        x = 0
        for j, (L, (a, b)) in enumerate(ents[i:i + CH]):
            assert 1 <= L < 1 << 22 and a < 1 << 66 and b < 1 << 66
            x |= (L | (a << 22) | (b << 88)) << (154 * j)
        out.append(x)
    return out
def lit_module(path, name, chunks, note, extra=()):
    subs = []
    L = [f"/-! {note} ({len(chunks)} chunks). Generated by M3/tools/gen_kfiles.py. -/", "", "namespace R45.M3.K", ""]
    for i in range(0, len(chunks), SUB):
        nm = f"{name}_{i // SUB}"; subs.append(nm)
        L.append(f"noncomputable def {nm} : List Nat := [" + ",\n  ".join(str(c) for c in chunks[i:i + SUB]) + "]")
        L.append("")
    L.append(f"noncomputable def {name} : List Nat := " + (" ++ ".join(subs) if subs else "[]"))
    L += [""] + list(extra) + ["", "end R45.M3.K", ""]
    open(path, "w").write("\n".join(L))
def shard(path, imports, body):
    opens = "open R45.M3 R45.M3.K" if any(m.startswith("Romanoff.M3.K.") for m in imports) else "open R45.M3"
    open(path, "w").write("\n".join([f"import {m}" for m in imports] + ["", opens, "", HDR, body, ""]))
if __name__ == "__main__":
    d = json.load(open(sys.argv[1])); plan = json.load(open(sys.argv[2])); out = sys.argv[3]
    BCH = int(sys.argv[4]) if len(sys.argv) > 4 else 6
    os.makedirs(out, exist_ok=True)
    sched = plan["sched"]
    A = [(p, t) for p, t in d["A"] if p not in ELL]; E = [(p, t) for p, t in d["A"] if p in ELL]
    gA, gE, gB = groups(A), groups(E), groups(d["B"])
    jobs = []
    # DP checkpoints
    tab = {1: (SC, SC)}; tabs = {}
    for k, (t, ps) in enumerate(gA, start=1):
        tab = step(tab, t, eLo(ps), eUp(ps))
        if k in sched:
            tabs[k] = (sorted(tab.items()), m3ref.DROP[0])
            lit_module(f"{out}/Tab{k}.lean", f"tab{k}", pack(tabs[k][0]),
                       f"DP table after {k} groups of gA ({len(tab)} entries)", [f"def drop{k} : Nat := {m3ref.DROP[0]}"])
    tT = dict(tab); dT = m3ref.DROP[0]
    for j in range(1, len(sched)):
        a, b = sched[j - 1], sched[j]
        src = "tab0 0" if a == 0 else f"(decTabK tab{a}) drop{a}"
        imps = ["RCert.M3.KFun", "RCert.M3.Data"] + ([f"Romanoff.M3.K.Tab{a}"] if a else []) + [f"Romanoff.M3.K.Tab{b}"]
        shard(f"{out}/KDP{j}.lean", imps,
              f"theorem kdp{j} : segOK {src} ((D.data.gA.drop {a}).take {b - a}) tab{b} drop{b} = true := by decide +kernel")
        work = sum(plan["sizes"][a:b])
        jobs.append((f"KDP{j}", 10 + work / 3500))
    # R table: one shard per gE step (intermediate tables tabR1 .. tabR8, final tabR)
    last = sched[-1]
    tR = dict(tT); prev = f"tab{last}"; prevmod = f"Romanoff.M3.K.Tab{last}"
    for k, (t, ps) in enumerate(gE, start=1):
        tR = step(tR, t, eLo(ps), eUp(ps))
        name = "tabR" if k == len(gE) else f"tabR{k}"
        mod = "TabR" if k == len(gE) else f"TabR{k}"
        lit_module(f"{out}/{mod}.lean", name, pack(sorted(tR.items())), f"R0 table after {k} groups of gE ({len(tR)} entries)")
        shard(f"{out}/KR{k}.lean", ["RCert.M3.KFun", "RCert.M3.Data", prevmod, f"Romanoff.M3.K.{mod}"],
              f"theorem kr{k} : segROK (decTabK {prev}) ((D.data.gE.drop {k - 1}).take 1) {name} = true := by decide +kernel")
        jobs.append((f"KR{k}", 10 + 2 * len(tR) / 3500))
        prev, prevmod = name, f"Romanoff.M3.K.{mod}"
    # subtables
    ents = sorted(tT.items())
    for h in DIV:
        sub = [(L, ab) for L, ab in ents if math.gcd(L, 120) == h]
        lit_module(f"{out}/Sub{h}.lean", f"sub{h}", pack(sub), f"subtable gcd(L, 120) = {h} of tab{last} ({len(sub)} entries)")
        shard(f"{out}/KSub{h}.lean", ["RCert.M3.KFun", f"Romanoff.M3.K.Tab{last}", f"Romanoff.M3.K.Sub{h}"],
              f"theorem ksub{h} : entsEqK (subK {h} (decTabK tab{last})) (decTabK sub{h}) = true := by decide +kernel")
        jobs.append((f"KSub{h}", 15))
    # values
    sA = sum(a for L, (a, b) in ents if 1 <= L <= LMAX); sB = sum(b for L, (a, b) in ents if 1 <= L <= LMAX)
    r0a = sum(a // L for L, (a, b) in tR.items() if 1 <= L <= LMAX)
    def accG(s):
        acc = [0] * 16
        for L, (a, b) in ents:
            if 1 <= L <= LMAX:
                L2 = L * s // math.gcd(L, s); g = math.gcd(L2, 120); acc[DIV.index(g)] += (b * g + L2 - 1) // L2
        return acc
    def sumR(u):
        return sum(a // (L * u // math.gcd(L, u)) for L, (a, b) in tR.items() if 1 <= L <= LMAX)
    acc1 = accG(1)
    subsl = ", ".join(f"({h}, decTabK sub{h})" for h in DIV)
    vals = ["import RCert.M3.KFun"] + [f"import Romanoff.M3.K.Sub{h}" for h in DIV] + ["",
            "/-! Pass values of the T and R0 tables. Generated by M3/tools/gen_kfiles.py. -/", "", "namespace R45.M3.K", "",
            f"def sA : Nat := {sA}", f"def sB : Nat := {sB}", f"def r0a : Nat := {r0a}", f"def dT : Nat := {dT}",
            f"def acc1 : List Nat := [{', '.join(map(str, acc1))}]",
            f"noncomputable def subsLit : List (Nat × List R45.M3.Ent) := [{subsl}]", "", "end R45.M3.K", ""]
    open(f"{out}/Vals.lean", "w").write("\n".join(vals))
    shard(f"{out}/KVsA.lean", ["RCert.M3.KFun", f"Romanoff.M3.K.Tab{last}", "Romanoff.M3.K.Vals"],
          f"theorem kvsA : Nat.beq (sumAK (decTabK tab{last})) sA = true := by decide +kernel")
    shard(f"{out}/KVsB.lean", ["RCert.M3.KFun", f"Romanoff.M3.K.Tab{last}", "Romanoff.M3.K.Vals"],
          f"theorem kvsB : Nat.beq (sumBK (decTabK tab{last})) sB = true := by decide +kernel")
    shard(f"{out}/KVr0a.lean", ["RCert.M3.KFun", "Romanoff.M3.K.TabR", "Romanoff.M3.K.Vals"],
          f"theorem kvr0a : Nat.beq (sumRK 1 (decTabK tabR)) r0a = true := by decide +kernel")
    shard(f"{out}/KVacc1.lean", ["RCert.M3.KFun", "Romanoff.M3.K.Vals"],
          f"theorem kvacc1 : (accSplitK 1 subsLit).1 = acc1 ∧ (accSplitK 1 subsLit).2 = true := by decide +kernel")
    jobs += [("KVsA", 20), ("KVsB", 20), ("KVr0a", 25), ("KVacc1", 30)]
    # class-B data
    bds = []
    for t, ps in gB:
        FU = sum(fUp(q) for q in ps); FL = sum(fLo(q) for q in ps)
        ex = FU >= 1e-12 * SC
        if ex: bds.append((FU, FL, t, True, accG(t), sumR(t)))
        else: bds.append((FU, FL, t, False, [], r0a // t))
    # chunks: each holds up to BCH exact groups
    chunks = []; cur = []; nex = 0
    for i, bd in enumerate(bds):
        cur.append(i); nex += bd[3]
        if nex >= BCH: chunks.append(cur); cur = []; nex = 0
    if cur: chunks.append(cur)
    L = ["import RCert.M3.Check", "", "/-! Class-B data (one list per chunk). Generated by M3/tools/gen_kfiles.py. -/", "",
         "namespace R45.M3.K", ""]
    for j, ch in enumerate(chunks):
        items = []
        for i in ch:
            FU, FL, t, ex, acc, r = bds[i]
            items.append(f"⟨{FU}, {FL}, {t}, {'true' if ex else 'false'}, [{', '.join(map(str, acc))}], {r}⟩")
        L.append(f"def bd{j} : List R45.M3.BD := [\n  " + ",\n  ".join(items) + "]")
        L.append("")
    L.append("def bsLit : List R45.M3.BD := " + " ++ ".join(f"bd{j}" for j in range(len(chunks))))
    L += ["", "end R45.M3.K", ""]
    open(f"{out}/BDs.lean", "w").write("\n".join(L))
    starts = []
    pos = 0
    for j, ch in enumerate(chunks):
        a, n = ch[0], len(ch)
        assert a == pos; pos += n; starts.append((a, n))
        shard(f"{out}/KB{j}.lean", ["RCert.M3.KFun", "RCert.M3.Data", "Romanoff.M3.K.TabR", "Romanoff.M3.K.Vals",
                                    "Romanoff.M3.K.BDs"],
              f"theorem kb{j} : bdChunkOK subsLit (decTabK tabR) r0a ((D.data.gB.drop {a}).take {n}) bd{j} = true := by\n  decide +kernel")
        nexc = sum(bds[i][3] for i in ch)
        jobs.append((f"KB{j}", 15 + 14 * nexc))
    # final
    shard(f"{out}/KF.lean", ["RCert.M3.KFun", "RCert.M3.Data", "RCert.M3.TeffLit", "Romanoff.M3.K.Vals", "Romanoff.M3.K.BDs"],
          "theorem kf : (teffOfV D.data acc1 sA sB dT r0a bsLit == teffLit) && Nat.ble sA (piUp D.data.gA) = true := by\n"
          "  decide +kernel")
    jobs.append(("KF", 60))
    # certificate shards
    nrec = len(d["recs"]); nchunk = (nrec + 249) // 250
    for i in range(nchunk):
        shard(f"{out}/KCr{i}.lean", ["RCert.M3.Data"], f"theorem kcr{i} : R45.M3.D.recs{i}.all recOK = true := by decide +kernel")
        jobs.append((f"KCr{i}", 30))
    shard(f"{out}/KCs.lean", ["RCert.M3.Data"],
          "theorem kcs : sortedLT (D.data.recs.map (·.n)) = true := by decide +kernel")
    shard(f"{out}/KCb.lean", ["RCert.M3.Data"],
          "theorem kcb : subSorted (sortNat (bigOnly (D.data.recs.flatMap fun r => r.fs.map (·.1)))) (D.data.recs.map (·.n))\n"
          "    = true := by decide +kernel")
    shard(f"{out}/KCg.lean", ["RCert.M3.Data"], "theorem kcg : D.data.groups.all grpOK = true := by decide +kernel")
    shard(f"{out}/KCp.lean", ["RCert.M3.Data"],
          "theorem kcp : primeOK (D.data.recs.map (·.n)) (D.data.groups.flatMap (·.ps)) = true := by decide +kernel")
    shard(f"{out}/KCm.lean", ["RCert.M3.Data"],
          "theorem kcm : (sortedLT (D.data.gA.map (·.t)) && sortedLT (D.data.gE.map (·.t)) && sortedLT (D.data.gB.map (·.1.t)) &&\n"
          "    D.data.gE.all (fun g => !(D.data.gA.map (·.t)).contains g.t) &&\n"
          "    D.data.gE.all (fun g => g.ps.all fun p => ellPs.contains p) &&\n"
          "    (D.data.gA ++ D.data.gE).all (fun g => g.t ≤ 300) && D.data.gB.all (fun g => 300 < g.1.t && g.1.t ≤ 1200)) = true := by\n"
          "  decide +kernel")
    jobs += [("KCs", 30), ("KCb", 60), ("KCg", 60), ("KCp", 60), ("KCm", 20)]
    with open(f"{out}/jobs.txt", "w") as f:
        for n, e in jobs: f.write(f"{n} {e:.0f}\n")
    json.dump(dict(sched=sched, last=last, bchunks=starts, nB=len(gB), nrecchunks=nchunk, nA=len(gA), nE=len(gE)),
              open(f"{out}/plan.json", "w"))
    print(f"DP shards {len(sched) - 1}, B chunks {len(chunks)}, rec chunks {nchunk}, jobs {len(jobs)}, "
          f"est total {sum(e for n, e in jobs):.0f} s")
