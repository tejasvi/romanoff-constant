"""Generate Romanoff/M3/KMain.lean (the K glue) from Romanoff/M3/K/plan.json.
usage: gen_kglue.py PLAN.json OUT.lean"""
import json, sys
p = json.load(open(sys.argv[1])); out = sys.argv[2]
sched, last, bch, nB, nrc, nA = p["sched"], p["last"], p["bchunks"], p["nB"], p["nrecchunks"], p["nA"]
DIV = [1, 2, 3, 4, 5, 6, 8, 10, 12, 15, 20, 24, 30, 40, 60, 120]
imps = ["Romanoff.M3.KGlue", "RCert.M3.TeffLit"]
imps += [f"Romanoff.M3.K.KDP{j}" for j in range(1, len(sched))]
nE = p.get("nE", 9)
imps += [f"Romanoff.M3.K.KR{k}" for k in range(1, nE + 1)] + [f"Romanoff.M3.K.KSub{h}" for h in DIV]
imps += ["Romanoff.M3.K.KVsA", "Romanoff.M3.K.KVsB", "Romanoff.M3.K.KVr0a", "Romanoff.M3.K.KVacc1"]
imps += [f"Romanoff.M3.K.KB{j}" for j in range(len(bch))] + ["Romanoff.M3.K.KF"]
imps += [f"Romanoff.M3.K.KCr{i}" for i in range(nrc)] + [f"Romanoff.M3.K.KC{x}" for x in "sbgpm"]
L = [f"import {m}" for m in imps] + ["", """/-!
# M3, K version: `TBound teffLit` from the kernel shards (generated by M3/tools/gen_kglue.py)

The DP checkpoints (`KDP*`), the R0 table (`KR`), the subtables (`KSub*`), the pass values (`KV*`), the class-B data
(`KB*`), the final evaluation (`KF`) and the certificate checks (`KC*`) are kernel-checked (`decide +kernel`); this file
chains them into `tbound_of`.
-/""", "", "namespace Romanoff.M3", "", "open R45.M3 R45.M3.K", "", "set_option maxRecDepth 100000", ""]
# DP chain
L.append(f"theorem runDPD_K : runDPD tab0 0 D.data.gA = (decTabK tab{last}, drop{last}) := by")
L.append("  show runDPD tab0 0 (D.data.gA.drop 0) = _")
for j in range(1, len(sched)):
    a, b = sched[j - 1], sched[j]
    L.append(f"  rw [seg_step _ _ (D.data.gA.drop {a}) {b - a} tab{b} drop{b} kdp{j}, drop_drop' _ {a} {b - a} {b} rfl]")
L.append(f"  rw [List.drop_eq_nil_of_le (by decide +kernel : D.data.gA.length ≤ {last})]")
L.append("  rfl")
L += ["", f"theorem tT_eq : runDP tab0 D.data.gA = decTabK tab{last} := by",
      "  have h := runDPD_K", "  rw [runDPD_eq] at h", "  exact (Prod.mk.inj h).1", "",
      f"theorem dT_eq : runDrop tab0 D.data.gA = dT := by",
      "  have h := runDPD_K", "  rw [runDPD_eq] at h", f"  have h2 : 0 + runDrop tab0 D.data.gA = drop{last} := (Prod.mk.inj h).2",
      f"  rw [Nat.zero_add] at h2", f"  rw [h2]", "  rfl", "",
      f"theorem tR_eq : runDP (decTabK tab{last}) D.data.gE = decTabK tabR := by",
      "  show runDP (decTabK tab%d) (D.data.gE.drop 0) = _" % last]
for k in range(1, nE + 1):
    nm = "tabR" if k == nE else f"tabR{k}"
    L.append(f"  rw [segR_step _ (D.data.gE.drop {k - 1}) 1 {nm} kr{k}, drop_drop' _ {k - 1} 1 {k} rfl]")
L += [f"  rw [List.drop_eq_nil_of_le (by decide +kernel : D.data.gE.length ≤ {nE})]", "  rfl", ""]
# subtables
for h in DIV:
    L.append(f"theorem sub{h}_eq : decTabK sub{h} = (decTabK tab{last}).filter fun x => keyH x == {h} := by")
    L.append(f"  rw [← subK_eq]; exact (entsEqK_eq _ _ ksub{h}).symm")
L += ["", f"theorem subs_eq : subsLit = div120.map fun h => (h, (decTabK tab{last}).filter fun x => keyH x == h) := by",
      "  simp only [subsLit, div120, List.map_cons, List.map_nil, " + ", ".join(f"sub{h}_eq" for h in DIV) + "]", ""]
L += [f"theorem sA_eq : sumA (decTabK tab{last}) = sA := by rw [← sumAK_eq]; exact beq_true kvsA",
      f"theorem sB_eq : sumB (decTabK tab{last}) = sB := by rw [← sumBK_eq]; exact beq_true kvsB",
      f"theorem r0a_eq : sumR 1 (decTabK tabR) = r0a := by rw [← sumRK_eq]; exact beq_true kvr0a",
      f"theorem acc1_eq : accG 1 (decTabK tab{last}) = acc1 := by",
      f"  exact accSplitK_sound' 1 _ subsLit subs_eq acc1 kvacc1.2 kvacc1.1", ""]
# class B chain
L.append(f"theorem bs_eq : bsOf D.data (decTabK tab{last}) (decTabK tabR) = bsLit := by")
L.append("  unfold bsOf")
L.append("  rw [r0a_eq]")
L.append(f"  show (D.data.gB.drop 0).map (mkBD (decTabK tab{last}) (decTabK tabR) r0a) = bsLit")
for j, (a, n) in enumerate(bch):
    L.append(f"  rw [map_seg _ (D.data.gB.drop {a}) {n} bd{j} (bdChunkOK_sound _ _ subsLit subs_eq r0a _ _ kb{j}), "
             f"drop_drop' _ {a} {n} {a + n} rfl]")
L.append(f"  rw [List.drop_eq_nil_of_le (by decide +kernel : D.data.gB.length ≤ {nB})]")
L.append("  simp only [List.map_nil, List.append_nil, bsLit, List.append_assoc]")
L += ["", f"theorem teff_eq : teffOf D.data (decTabK tab{last}) dT (decTabK tabR) bsLit = teffLit := by",
      "  rw [teffOf_eq_V, acc1_eq, sA_eq, sB_eq, r0a_eq]",
      "  exact eq_of_beq ((Bool.and_eq_true _ _).mp kf).1", "",
      "theorem sumsOK_K : sumsOK D.data (runDP tab0 D.data.gA) = true := by",
      "  rw [tT_eq]", "  unfold sumsOK", "  rw [sA_eq]",
      "  exact decide_eq_true (Nat.ble_eq.mp ((Bool.and_eq_true _ _).mp kf).2)", ""]
# cert
L.append("theorem recs_all : D.data.recs.all recOK = true := by")
L.append("  show (" + " ++ ".join(f"R45.M3.D.recs{i}" for i in range(nrc)) + ").all recOK = true")
L.append("  simp only [List.all_append, " + ", ".join(f"kcr{i}" for i in range(nrc)) + ", Bool.and_self]")
L += ["", "theorem certOK_K : certOK D.data = true := by",
      "  have hm := kcm",
      "  simp only [Bool.and_eq_true] at hm",
      "  unfold certOK prattOK",
      "  simp only [Bool.and_eq_true]",
      "  exact ⟨⟨⟨⟨⟨⟨⟨⟨⟨⟨⟨kcs, recs_all⟩, kcb⟩, kcg⟩, kcp⟩, hm.1.1.1.1.1.1⟩, hm.1.1.1.1.1.2⟩, hm.1.1.1.1.2⟩, hm.1.1.1.2⟩,",
      "    hm.1.1.2⟩, hm.1.2⟩, hm.2⟩", "",
      "/-- The certified `T(c)` bounds (literals), kernel-checked. -/",
      "theorem tboundLitK (h5 : R0Bound) : TBound teffLit := by",
      "  have h := tbound_of D.data certOK_K sumsOK_K h5",
      "  rw [dT_eq, tT_eq, tR_eq, bs_eq, teff_eq] at h",
      "  exact h", "", "end Romanoff.M3", ""]
open(out, "w").write("\n".join(L))
print("wrote", out, len(L), "lines")
