"""Generate RCert/E/EvData.lean: constants of the U3e stage-2 evaluator (divisors, count plan, lcm indices,
B_g on the 2^-36 grid, the order of the options of 37, the Pintz-index constants)."""
import re, sys, math
from fractions import Fraction as Fr
ROOT = sys.argv[1]
divE = [g for g in range(1, 3961) if 3960 % g == 0]
src = open(f"{ROOT}/RCert/M3E/Defs.lean").read()
m = re.search(r"def divE : List Nat := \[([^\]]*)\]", src)
assert [int(t) for t in m.group(1).replace("\n", " ").split(",")] == divE
blit = open(f"{ROOT}/RCert/E/BLit.lean").read()
B = {}
for g, a, b in re.findall(r"\((\d+), \((\d+) : Rat\) / (\d+)\)", blit):
    B[int(g)] = Fr(int(a), int(b))
assert sorted(B) == divE, sorted(B)
E = 36
bn = [-((-B[g].numerator * 2 ** E) // B[g].denominator) for g in divE]
assert all(Fr(b, 2 ** E) >= B[g] for b, g in zip(bn, divE))
def spf(n):
    d = 2
    while n % d: d += 1
    return d
idx = {g: i for i, g in enumerate(divE)}
plan = []
for g in sorted(divE, reverse=True):
    if g == 3960: continue
    q = spf(3960 // g)
    plan.append((idx[g], idx[g * q], q))
lidx = [idx[g * 36 // math.gcd(g, 36)] for g in divE]
o37 = []
for r in range(37):
    js = [j for j in range(36) if pow(2, j, 37) == r]
    if js: o37.append(js[0])
assert sorted(o37) == list(range(36))
# kappa, R0t
C0up = Fr(33008090792343479, 50000000000000000); log2lo = Fr(693147180559945309, 10 ** 18)
ELL = [3, 5, 7, 11, 13, 17, 31, 241, 41, 19, 73, 23, 37]
pell = Fr(1)
for p in ELL: pell *= Fr(p - 1, p - 2)
kap = C0up * pell / (3960 * log2lo)
R0t = Fr(1411128035385039641, 7205759403792793600000)
KM = round(8 * kap * 2 ** 28)
KC = round(8 * kap * 3960 * R0t * 2 ** 56)
cost = sum(divE[I] for i, I, q in plan)
print(f"kap={float(kap):.6e} KM={KM} KC={KC} plan cost={cost} sum lcm={sum(divE[l] for l in lidx)}", file=sys.stderr)
L = []
L.append("import RCert.M3E.Defs")
L.append("")
L.append("/-! U3e stage 2: constants of the evaluator (generated by u3e/tools/gen_ev.py). -/")
L.append("")
L.append("namespace R45.EV")
L.append("")
L.append("/-- The divisors of 3960 (the order of `divE`). -/")
L.append("def dA : Array Nat := #[" + ", ".join(map(str, divE)) + "]")
L.append("")
L.append("/-- `⌈B_g 2^36⌉` for the divisors `g` (order of `divE`). -/")
L.append("def bnA : Array Nat := #[" + ", ".join(map(str, bn)) + "]")
L.append("")
L.append("/-- The count plan `(i, I, q)`: `dA[I] = q dA[i]`, parents before children. -/")
L.append("def plan : List (Nat × Nat × Nat) := [" + ", ".join(f"({a}, {b}, {c})" for a, b, c in plan) + "]")
L.append("")
L.append("/-- The index of `lcm(dA[i], 36)`. -/")
L.append("def lIdx : Array Nat := #[" + ", ".join(map(str, lidx)) + "]")
L.append("")
L.append("/-- The classes `j mod 36` of the options `r = 2^j mod 37`, in increasing `r`. -/")
L.append("def o37 : List Nat := [" + ", ".join(map(str, o37)) + "]")
L.append("")
L.append("/-- Constants of the Pintz index (tightness only): `8 κ 2^28` and `8 κ 3960 R0t 2^56`, rounded. -/")
L.append(f"def KM : Nat := {KM}")
L.append(f"def KC : Nat := {KC}")
L.append("")
L.append("end R45.EV")
open(f"{ROOT}/RCert/E/EvData.lean", "w").write("\n".join(L) + "\n")
