"""Generate the K-version literal modules and kernel shards for M3 at period 27720 (U3g/V4g modulus G):
Romanoff/G/M3/K/*.lean. The period-27720 counterpart of gen_kfiles.py (same DP literals and shards, the G prime list,
96 divisors), with the final evaluation replaced by two checks at the 96 divisors of 27720 (see Romanoff/G/M3/KGcd.lean).

usage: gen_kfiles_g.py PRATT.json KPLAN_G.json OUTDIR [BCHUNK]
Literals (noncomputable defs, namespace R45.M3G.K): Tab<k> (DP checkpoints, with drop<k>), TabR<k>/TabR (R0 table after
each gE group), Sub<h> (subtables of the last Tab by gcd(L, 27720) = h, 96 of them), Vals (sA sB r0a dT acc1 subsLit vals96),
BDs (class-B data in chunks, bsLit).
Shards (one theorem each, `decide +kernel`, namespace R45.M3G.KS): KDP<j>, KR<k>, KSub<h>, KVsA, KVsB, KVr0a, KVacc1, KB<j>, KV96 (the values
at the divisors and sumA <= piUp), KTB (the divisor sums of BLit), KCr<i>, KCs, KCb, KCg, KCp, KCm (certOK, split).
Writes OUTDIR/jobs.txt (name est_seconds) and OUTDIR/plan.json (what the glue needs)."""
import json, sys, os, math
sys.set_int_max_str_digits(0)
os.environ.setdefault("KAPPA", "16384")
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import m3ref
from m3ref import groups, step, eLo, eUp, fUp, fLo, SC, LMAX
ELL = [3, 5, 7, 11, 13, 17, 31, 241, 41, 19, 73, 37, 23, 43, 29]
PER = 27720
DIV = [g for g in range(1, PER + 1) if PER % g == 0]
assert len(DIV) == 96
CH = 64; SUB = 256
HDR = "set_option maxHeartbeats 0\nset_option maxRecDepth 100000\n"
MOD = "Romanoff.G.M3.K"
DATA = "R45.M3G.D.data"
def pack(ents):
    out = []
    for i in range(0, len(ents), CH):
        x = 0
        for j, (L, (a, b)) in enumerate(ents[i:i + CH]):
            assert 1 <= L < 1 << 22 and a < 1 << 66 and b < 1 << 66
            x |= (L | (a << 22) | (b << 88)) << (154 * j)
        out.append(x)
    return out
def lit_module(path, name, chunks, note, extra=()):
    subs = []
    L = [f"/-! {note} ({len(chunks)} chunks). Generated by M3/tools/gen_kfiles_g.py. -/", "", "namespace R45.M3G.K", ""]
    for i in range(0, len(chunks), SUB):
        nm = f"{name}_{i // SUB}"; subs.append(nm)
        L.append(f"noncomputable def {nm} : List Nat := [" + ",\n  ".join(str(c) for c in chunks[i:i + SUB]) + "]")
        L.append("")
    L.append(f"noncomputable def {name} : List Nat := " + (" ++ ".join(subs) if subs else "[]"))
    L += [""] + list(extra) + ["", "end R45.M3G.K", ""]
    open(path, "w").write("\n".join(L))
def shard(path, imports, body):
    opens = "open R45.M3 R45.M3G.K" if any(m.startswith(MOD + ".") for m in imports) else "open R45.M3"
    open(path, "w").write("\n".join([f"import {m}" for m in imports] +
                                    ["", opens, "", HDR, "namespace R45.M3G.KS", "", body, "", "end R45.M3G.KS", ""]))
def cdiv(x, y): return (x + y - 1) // y
def mulUp(x, y): return (x * y + SC - 1) // SC
def sumDvd(acc, c): return sum(a for g, a in zip(DIV, acc) if c % g == 0)
if __name__ == "__main__":
    d = json.load(open(sys.argv[1])); plan = json.load(open(sys.argv[2])); out = sys.argv[3]
    BCH = int(sys.argv[4]) if len(sys.argv) > 4 else 6
    os.makedirs(out, exist_ok=True)
    sched = plan["sched"]
    A = [(p, t) for p, t in d["A"] if p not in ELL]; E = [(p, t) for p, t in d["A"] if p in ELL]
    gA, gE, gB = groups(A), groups(E), groups(d["B"])
    jobs = []
    KF = ["RCert.M3.KFun", "RCert.M3G.KFun", "RCert.M3G.Data"]
    # DP checkpoints
    tab = {1: (SC, SC)}
    for k, (t, ps) in enumerate(gA, start=1):
        tab = step(tab, t, eLo(ps), eUp(ps))
        if k in sched:
            lit_module(f"{out}/Tab{k}.lean", f"tab{k}", pack(sorted(tab.items())),
                       f"DP table after {k} groups of gA, period-27720 modulus ({len(tab)} entries)",
                       [f"def drop{k} : Nat := {m3ref.DROP[0]}"])
    tT = dict(tab); dT = m3ref.DROP[0]
    for j in range(1, len(sched)):
        a, b = sched[j - 1], sched[j]
        src = "tab0 0" if a == 0 else f"(decTabK tab{a}) drop{a}"
        imps = KF + ([f"{MOD}.Tab{a}"] if a else []) + [f"{MOD}.Tab{b}"]
        shard(f"{out}/KDP{j}.lean", imps,
              f"theorem kdp{j} : segOK {src} (({DATA}.gA.drop {a}).take {b - a}) tab{b} drop{b} = true := by decide +kernel")
        work = sum(plan["sizes"][a:b])
        jobs.append((f"KDP{j}", 10 + work / 3500))
    # R table: one shard per gE step
    last = sched[-1]
    tR = dict(tT); prev = f"tab{last}"; prevmod = f"{MOD}.Tab{last}"
    for k, (t, ps) in enumerate(gE, start=1):
        tR = step(tR, t, eLo(ps), eUp(ps))
        name = "tabR" if k == len(gE) else f"tabR{k}"
        mod = "TabR" if k == len(gE) else f"TabR{k}"
        lit_module(f"{out}/{mod}.lean", name, pack(sorted(tR.items())), f"R0 table after {k} groups of gE ({len(tR)} entries)")
        shard(f"{out}/KR{k}.lean", KF + [prevmod, f"{MOD}.{mod}"],
              f"theorem kr{k} : segROK (decTabK {prev}) (({DATA}.gE.drop {k - 1}).take 1) {name} = true := by decide +kernel")
        jobs.append((f"KR{k}", 10 + 2 * len(tR) / 3500))
        prev, prevmod = name, f"{MOD}.{mod}"
    # subtables by gcd(L, 27720)
    ents = sorted(tT.items())
    for h in DIV:
        sub = [(L, ab) for L, ab in ents if math.gcd(L, PER) == h]
        lit_module(f"{out}/Sub{h}.lean", f"sub{h}", pack(sub), f"subtable gcd(L, 27720) = {h} of tab{last} ({len(sub)} entries)")
        shard(f"{out}/KSub{h}.lean", KF + [f"{MOD}.Tab{last}", f"{MOD}.Sub{h}"],
              f"theorem ksub{h} : entsEqK (R45.M3G.subKG {h} (decTabK tab{last})) (decTabK sub{h}) = true := by decide +kernel")
        jobs.append((f"KSub{h}", 15))
    # values
    sA = sum(a for L, (a, b) in ents if 1 <= L <= LMAX); sB = sum(b for L, (a, b) in ents if 1 <= L <= LMAX)
    r0a = sum(a // L for L, (a, b) in tR.items() if 1 <= L <= LMAX)
    def accG(s):
        acc = [0] * 96
        for L, (a, b) in ents:
            if 1 <= L <= LMAX:
                L2 = L * s // math.gcd(L, s); g = math.gcd(L2, PER); acc[DIV.index(g)] += (b * g + L2 - 1) // L2
        return acc
    def sumR(u):
        return sum(a // (L * u // math.gcd(L, u)) for L, (a, b) in tR.items() if 1 <= L <= LMAX)
    acc1 = accG(1)
    # class-B data
    bds = []
    for t, ps in gB:
        FU = sum(fUp(q) for q in ps); FL = sum(fLo(q) for q in ps)
        ex = FU >= 1e-12 * SC
        if ex: bds.append((FU, FL, t, True, accG(t), sumR(t)))
        else: bds.append((FU, FL, t, False, [], r0a // t))
    # the values tabNumV at the 96 divisors (Romanoff/G/M3/KGcd.lean)
    piU = SC
    for t, ps in gA: piU = mulUp(piU, SC + eUp(ps))
    prM = piU - sA
    def tabNum(c):
        g = math.gcd(c, PER)
        prc = cdiv(prM * g, LMAX) + cdiv(g * piU * dT, SC)
        tb = sum(mulUp(FU, (sumDvd(acc, c) if ex else cdiv(sB * g, t)) + prc) for FU, FL, t, ex, acc, r in bds)
        return sumDvd(acc1, c) + prc + tb
    vals96 = [tabNum(dd) for dd in DIV]
    subsl = ", ".join(f"({h}, R45.M3.decTabK sub{h})" for h in DIV)
    vals = ["import RCert.M3.KFun"] + [f"import {MOD}.Sub{h}" for h in DIV] + ["",
            "/-! Pass values of the T and R0 tables, period 27720. Generated by M3/tools/gen_kfiles_g.py. -/", "",
            "namespace R45.M3G.K", "",
            f"def sA : Nat := {sA}", f"def sB : Nat := {sB}", f"def r0a : Nat := {r0a}", f"def dT : Nat := {dT}",
            f"def acc1 : List Nat := [{', '.join(map(str, acc1))}]",
            f"def vals96 : List Nat := [{', '.join(map(str, vals96))}]",
            f"noncomputable def subsLit : List (Nat × List R45.M3.Ent) := [{subsl}]", "", "end R45.M3G.K", ""]
    open(f"{out}/Vals.lean", "w").write("\n".join(vals))
    shard(f"{out}/KVsA.lean", KF + [f"{MOD}.Tab{last}", f"{MOD}.Vals"],
          f"theorem kvsA : Nat.beq (sumAK (decTabK tab{last})) sA = true := by decide +kernel")
    shard(f"{out}/KVsB.lean", KF + [f"{MOD}.Tab{last}", f"{MOD}.Vals"],
          f"theorem kvsB : Nat.beq (sumBK (decTabK tab{last})) sB = true := by decide +kernel")
    shard(f"{out}/KVr0a.lean", KF + [f"{MOD}.TabR", f"{MOD}.Vals"],
          f"theorem kvr0a : Nat.beq (sumRK 1 (decTabK tabR)) r0a = true := by decide +kernel")
    shard(f"{out}/KVacc1.lean", KF + [f"{MOD}.Vals"],
          f"theorem kvacc1 : (R45.M3G.accSplitKG 1 subsLit).1 = acc1 ∧ (R45.M3G.accSplitKG 1 subsLit).2 = true := by decide +kernel")
    jobs += [("KVsA", 20), ("KVsB", 20), ("KVr0a", 25), ("KVacc1", 60)]
    # class-B chunks
    chunks = []; cur = []; nex = 0
    for i, bd in enumerate(bds):
        cur.append(i); nex += bd[3]
        if nex >= BCH: chunks.append(cur); cur = []; nex = 0
    if cur: chunks.append(cur)
    L = ["import RCert.M3.Check", "", "/-! Class-B data, period 27720 (one list per chunk). Generated by M3/tools/gen_kfiles_g.py. -/",
         "", "namespace R45.M3G.K", ""]
    for j, ch in enumerate(chunks):
        items = []
        for i in ch:
            FU, FL, t, ex, acc, r = bds[i]
            items.append(f"⟨{FU}, {FL}, {t}, {'true' if ex else 'false'}, [{', '.join(map(str, acc))}], {r}⟩")
        L.append(f"def bd{j} : List R45.M3.BD := [\n  " + ",\n  ".join(items) + "]")
        L.append("")
    L.append("def bsLit : List R45.M3.BD := " + " ++ ".join(f"bd{j}" for j in range(len(chunks))))
    L += ["", "end R45.M3G.K", ""]
    open(f"{out}/BDs.lean", "w").write("\n".join(L))
    starts = []
    pos = 0
    for j, ch in enumerate(chunks):
        a, n = ch[0], len(ch)
        assert a == pos; pos += n; starts.append((a, n))
        shard(f"{out}/KB{j}.lean", KF + [f"{MOD}.TabR", f"{MOD}.Vals", f"{MOD}.BDs"],
              f"theorem kb{j} : R45.M3G.bdChunkOKG subsLit (decTabK tabR) r0a (({DATA}.gB.drop {a}).take {n}) bd{j} = true := by\n"
              "  decide +kernel")
        nexc = sum(bds[i][3] for i in ch)
        jobs.append((f"KB{j}", 15 + 14 * nexc))
    # the values at the divisors and sumA <= piUp; the divisor sums of BLit
    shard(f"{out}/KV96.lean", KF + [f"{MOD}.Vals", f"{MOD}.BDs"],
          f"theorem kv96 : (R45.M3G.valsOK {DATA} acc1 sA sB dT bsLit vals96 && Nat.ble sA (piUp {DATA}.gA)) = true := by\n"
          "  decide +kernel")
    shard(f"{out}/KTB.lean", ["RCert.M3G.KFun", "RCert.G.BLit", f"{MOD}.Vals"],
          "theorem ktb : R45.M3G.tabBOK R45.U3G.BLit vals96 = true := by decide +kernel")
    jobs += [("KV96", 600), ("KTB", 60)]
    # certificate shards (certOK of RCert/M3G/Defs.lean, split)
    nrec = len(d["recs"]); nchunk = (nrec + 249) // 250
    for i in range(nchunk):
        shard(f"{out}/KCr{i}.lean", ["RCert.M3G.Data"], f"theorem kcr{i} : R45.M3G.D.recs{i}.all recOK = true := by decide +kernel")
        jobs.append((f"KCr{i}", 30))
    shard(f"{out}/KCs.lean", ["RCert.M3G.Data"],
          f"theorem kcs : sortedLT ({DATA}.recs.map (·.n)) = true := by decide +kernel")
    shard(f"{out}/KCb.lean", ["RCert.M3G.Data"],
          f"theorem kcb : subSorted (sortNat (bigOnly ({DATA}.recs.flatMap fun r => r.fs.map (·.1)))) ({DATA}.recs.map (·.n))\n"
          "    = true := by decide +kernel")
    shard(f"{out}/KCg.lean", ["RCert.M3G.Data"], f"theorem kcg : {DATA}.groups.all grpOK = true := by decide +kernel")
    shard(f"{out}/KCp.lean", ["RCert.M3G.Data"],
          f"theorem kcp : primeOK ({DATA}.recs.map (·.n)) ({DATA}.groups.flatMap (·.ps)) = true := by decide +kernel")
    shard(f"{out}/KCm.lean", ["RCert.M3G.Data"],
          f"theorem kcm : (sortedLT ({DATA}.gA.map (·.t)) && sortedLT ({DATA}.gE.map (·.t)) && sortedLT ({DATA}.gB.map (·.1.t)) &&\n"
          f"    {DATA}.gA.all (fun g => g.ps.all fun p => !R45.M3G.ellPs.contains p) &&\n"
          f"    {DATA}.gE.all (fun g => g.ps.all fun p => R45.M3G.ellPs.contains p) &&\n"
          f"    ({DATA}.gA ++ {DATA}.gE).all (fun g => g.t ≤ 300) && {DATA}.gB.all (fun g => 300 < g.1.t && g.1.t ≤ 1200)) = true := by\n"
          "  decide +kernel")
    jobs += [("KCs", 30), ("KCb", 60), ("KCg", 60), ("KCp", 60), ("KCm", 30)]
    with open(f"{out}/jobs.txt", "w") as f:
        for n, e in jobs: f.write(f"{n} {e:.0f}\n")
    json.dump(dict(sched=sched, last=last, bchunks=starts, nB=len(gB), nrecchunks=nchunk, nA=len(gA), nE=len(gE)),
              open(f"{out}/plan.json", "w"))
    print(f"gA {len(gA)} gE {len(gE)} gB {len(gB)} (exact {sum(b[3] for b in bds)}); T {len(tT)} entries, R {len(tR)}; "
          f"DP shards {len(sched) - 1}, B chunks {len(chunks)}, rec chunks {nchunk}, jobs {len(jobs)}, "
          f"est total {sum(e for n, e in jobs):.0f} s; nonempty subtables {sum(1 for h in DIV if any(math.gcd(L, PER) == h for L, _ in ents))}")
