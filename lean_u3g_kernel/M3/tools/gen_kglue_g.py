"""Generate Romanoff/G/M3/KMain.lean (the K glue of M3 at period 27720) from Romanoff/G/M3/K/plan.json.
The period-27720 counterpart of gen_kglue.py: the same DP, R0 table, subtable, pass-value, class-B and certificate chains,
for the data R45.M3G.D.data, the 96 subtables, and the checks at the 96 divisors (KV96, KTB) in place of the final
evaluation.
usage: gen_kglue_g.py PLAN.json OUT.lean"""
import json, sys
p = json.load(open(sys.argv[1])); out = sys.argv[2]
sched, last, bch, nB, nrc, nE = p["sched"], p["last"], p["bchunks"], p["nB"], p["nrecchunks"], p["nE"]
PER = 27720
DIV = [g for g in range(1, PER + 1) if PER % g == 0]
M = "Romanoff.G.M3.K"
D = "R45.M3G.D.data"
imps = ["Romanoff.M3.KGlue", "Romanoff.G.M3.KGcd", "RCert.M3G.KFun"]
imps += [f"{M}.KDP{j}" for j in range(1, len(sched))]
imps += [f"{M}.KR{k}" for k in range(1, nE + 1)] + [f"{M}.KSub{h}" for h in DIV]
imps += [f"{M}.KVsA", f"{M}.KVsB", f"{M}.KVr0a", f"{M}.KVacc1"]
imps += [f"{M}.KB{j}" for j in range(len(bch))] + [f"{M}.KV96", f"{M}.KTB"]
imps += [f"{M}.KCr{i}" for i in range(nrc)] + [f"{M}.KC{x}" for x in "sbgpm"]
L = [f"import {m}" for m in imps] + ["", """/-!
# M3 at period 27720, K version: the glue (generated by M3/tools/gen_kglue_g.py)

The DP checkpoints (`KDP*`), the R0 table (`KR*`), the 96 subtables (`KSub*`), the pass values (`KV*`), the class-B data
(`KB*`), the values at the 96 divisors and `sumA ≤ ∏` (`KV96`), the divisor sums of `BLit` (`KTB`) and the certificate
checks (`KC*`) are kernel-checked (`decide +kernel`, namespace `R45.M3G.KS`); this file chains them into the equations
that `Romanoff.G.K.tboundALitK` (Romanoff/G/LitK.lean) uses.
-/""", "", "namespace Romanoff.G.MK", "",
    "open R45.M3 hiding PER accG sumDvd certOK ellPs mkBD prC drC tbC teffOf bsOf teffD",
    "open R45.M3G R45.M3G.K R45.M3G.KS",
    "open Romanoff.M3 (seg_step segR_step map_seg drop_drop' beq_true entsEqK_eq sumAK_eq sumBK_eq sumRK_eq runDPD_eq)",
    "", "set_option maxRecDepth 100000", ""]
# DP chain
L.append(f"theorem runDPD_K : runDPD tab0 0 {D}.gA = (decTabK tab{last}, drop{last}) := by")
L.append(f"  show runDPD tab0 0 ({D}.gA.drop 0) = _")
for j in range(1, len(sched)):
    a, b = sched[j - 1], sched[j]
    L.append(f"  rw [seg_step _ _ ({D}.gA.drop {a}) {b - a} tab{b} drop{b} kdp{j}, drop_drop' _ {a} {b - a} {b} rfl]")
L.append(f"  rw [List.drop_eq_nil_of_le (by decide +kernel : {D}.gA.length ≤ {last})]")
L.append("  rfl")
L += ["", f"theorem tT_eq : runDP tab0 {D}.gA = decTabK tab{last} := by",
      "  have h := runDPD_K", "  rw [runDPD_eq] at h", "  exact (Prod.mk.inj h).1", "",
      f"theorem dT_eq : runDrop tab0 {D}.gA = dT := by",
      "  have h := runDPD_K", "  rw [runDPD_eq] at h", f"  have h2 : 0 + runDrop tab0 {D}.gA = drop{last} := (Prod.mk.inj h).2",
      "  rw [Nat.zero_add] at h2", "  rw [h2]", "  rfl", "",
      f"theorem tR_eq : runDP (decTabK tab{last}) {D}.gE = decTabK tabR := by",
      f"  show runDP (decTabK tab{last}) ({D}.gE.drop 0) = _"]
for k in range(1, nE + 1):
    nm = "tabR" if k == nE else f"tabR{k}"
    L.append(f"  rw [segR_step _ ({D}.gE.drop {k - 1}) 1 {nm} kr{k}, drop_drop' _ {k - 1} 1 {k} rfl]")
L += [f"  rw [List.drop_eq_nil_of_le (by decide +kernel : {D}.gE.length ≤ {nE})]", "  rfl", ""]
# subtables
for h in DIV:
    L.append(f"theorem sub{h}_eq : decTabK sub{h} = (decTabK tab{last}).filter fun x => keyH x == {h} := by")
    L.append(f"  rw [← subKG_eq]; exact (entsEqK_eq _ _ ksub{h}).symm")
L += ["", f"theorem subs_eq : subsLit = divG.map fun h => (h, (decTabK tab{last}).filter fun x => keyH x == h) := by",
      "  simp only [subsLit, divG, List.map_cons, List.map_nil, " + ", ".join(f"sub{h}_eq" for h in DIV) + "]", ""]
L += [f"theorem sA_eq : sumA (decTabK tab{last}) = sA := by rw [← sumAK_eq]; exact beq_true kvsA",
      f"theorem sB_eq : sumB (decTabK tab{last}) = sB := by rw [← sumBK_eq]; exact beq_true kvsB",
      f"theorem r0a_eq : sumR 1 (decTabK tabR) = r0a := by rw [← sumRK_eq]; exact beq_true kvr0a",
      f"theorem acc1_eq : accG 1 (decTabK tab{last}) = acc1 :=",
      f"  accSplitKG_sound 1 _ subsLit subs_eq acc1 (Prod.ext kvacc1.1 kvacc1.2)", ""]
# class B chain
L.append(f"theorem bs_eq : bsOf {D} (decTabK tab{last}) (decTabK tabR) = bsLit := by")
L.append("  unfold bsOf")
L.append("  rw [r0a_eq]")
L.append(f"  show ({D}.gB.drop 0).map (mkBD (decTabK tab{last}) (decTabK tabR) r0a) = bsLit")
for j, (a, n) in enumerate(bch):
    L.append(f"  rw [map_seg _ ({D}.gB.drop {a}) {n} bd{j} (bdChunkOKG_sound _ _ subsLit subs_eq r0a _ _ kb{j}), "
             f"drop_drop' _ {a} {n} {a + n} rfl]")
L.append(f"  rw [List.drop_eq_nil_of_le (by decide +kernel : {D}.gB.length ≤ {nB})]")
L.append("  simp only [List.map_nil, List.append_nil, bsLit, List.append_assoc]")
L += ["", f"theorem sumsOK_K : sumsOK {D} (runDP tab0 {D}.gA) = true := by",
      "  rw [tT_eq]", "  unfold sumsOK", "  rw [sA_eq]",
      "  exact decide_eq_true (Nat.ble_eq.mp ((Bool.and_eq_true _ _).mp kv96).2)", "",
      f"theorem valsOK_K : valsOK {D} (accG 1 (decTabK tab{last})) (sumA (decTabK tab{last})) (sumB (decTabK tab{last})) dT",
      "    bsLit vals96 = true := by",
      "  rw [acc1_eq, sA_eq, sB_eq]", "  exact ((Bool.and_eq_true _ _).mp kv96).1", ""]
# cert
L.append(f"theorem recs_all : {D}.recs.all recOK = true := by")
L.append("  show (" + " ++ ".join(f"R45.M3G.D.recs{i}" for i in range(nrc)) + ").all recOK = true")
L.append("  simp only [List.all_append, " + ", ".join(f"kcr{i}" for i in range(nrc)) + ", Bool.and_self]")
L += ["", f"theorem certOK_K : certOK {D} = true := by",
      "  have hm := kcm",
      "  simp only [Bool.and_eq_true] at hm",
      "  unfold certOK prattOK",
      "  simp only [Bool.and_eq_true]",
      "  exact ⟨⟨⟨⟨⟨⟨⟨⟨⟨⟨⟨kcs, recs_all⟩, kcb⟩, kcg⟩, kcp⟩, hm.1.1.1.1.1.1⟩, hm.1.1.1.1.1.2⟩, hm.1.1.1.1.2⟩, hm.1.1.1.2⟩,",
      "    hm.1.1.2⟩, hm.1.2⟩, hm.2⟩", "", "end Romanoff.G.MK", ""]
open(out, "w").write("\n".join(L))
print("wrote", out, len(L), "lines")
