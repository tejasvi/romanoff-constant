# k45g: write GK/GlueTotal.lean from the chunk totals GK/Glue/C000.T .. C063.T (Lean syntax of trees, written by GK/GenGlue3.lean):
# TOT = slotwise sum of the 64 chunk trees (checked again by the kernel in chunks_T_eq).
import re, sys
glue = sys.argv[1]; out = sys.argv[2]
def parse(s):
    toks = re.findall(r"\(|\)|\.leaf|\.node|\d+", s)
    pos = 0
    def tree():
        nonlocal pos
        assert toks[pos] == "("; pos += 1
        if toks[pos] == ".leaf":
            a, q = int(toks[pos + 1]), int(toks[pos + 2]); pos += 3
            assert toks[pos] == ")"; pos += 1
            return ("L", a, q)
        assert toks[pos] == ".node"; pos += 1
        l = tree(); r = tree()
        assert toks[pos] == ")"; pos += 1
        return ("N", l, r)
    t = tree(); assert pos == len(toks)
    return t
def add(t, s):
    if t[0] == "L": assert s[0] == "L"; return ("L", t[1] + s[1], t[2] + s[2])
    return ("N", add(t[1], s[1]), add(t[2], s[2]))
def lean(t):
    return f"(.leaf {t[1]} {t[2]})" if t[0] == "L" else f"(.node {lean(t[1])} {lean(t[2])})"
def zero(d):
    return ("L", 0, 0) if d == 0 else ("N", zero(d - 1), zero(d - 1))
tot = zero(6)
for n in range(64):
    tot = add(tot, parse(open(f"{glue}/C{n:03d}.T").read()))
names = [f"C{n:03d}" for n in range(64)]
imports = "\n".join(f"import GK.Glue.{c}" for c in names)
Ts = ", ".join(f"{c}.T" for c in names)
eqs = ", ".join(f"{c}.chunk_eq hvt" for c in names)
src = f"""import GK.Spec5
import GK.Glue3
import K45G.LG
{imports}

/-! k45g: the sum over all 7,871 BASE keys (K45G.LG, 64 chunks); generated by gen/gen_glue_total.py. -/

set_option maxRecDepth 100000
set_option maxHeartbeats 0

open Finset R45 R45.EVG Romanoff.G.S2

namespace R45.GK

def TOT : Acc := {lean(tot)}

theorem chunks_T_eq : [{Ts}].foldl Acc.plus (Acc.zero 6) = TOT := (Acc.beq_iff _ _).mp (by decide +kernel)

theorem chunks_T_wf : ([{Ts}].all (Acc.wfb 6)) = true := by decide +kernel

theorem total_eq {{vt : ℕ → ℕ → ℕ → ℚ}} (hvt : Lin vt) :
    (K45G.LG.map fun xc => (xc.2 : ℚ) * VfA vt (evalKeyK xc.1)).sum = VfA vt TOT := by
  rw [K45G.LG, ← sum_flatten_map (fun xc => (xc.2 : ℚ) * VfA vt (evalKeyK xc.1)) K45G.LGchunks]
  simp only [K45G.LGchunks, List.map_cons, List.map_nil, {eqs}]
  have hwf : ∀ t ∈ [{Ts}], Acc.WF 6 t := fun t ht => Acc.wf_of_wfb 6 t (List.all_eq_true.mp chunks_T_wf t ht)
  have h := sum_VfA_eq hvt [{Ts}] hwf TOT chunks_T_eq
  simpa only [List.map_cons, List.map_nil] using h

end R45.GK
"""
open(out, "w").write(src)
print("wrote", out, "TOT slots", sum(1 for _ in re.finditer("leaf", lean(tot))))
