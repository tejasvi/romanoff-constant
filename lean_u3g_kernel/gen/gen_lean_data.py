# k45g: generate GK/Data.lean (literal tables for the kernel-only fibered evaluator) from
#   - gen/sig_data_v1.json (gen_sig_data.py: the 412 signatures of F = (19, 73, 37) in the optsP conventions of RCert/G/Ev.lean), and
#   - RCert/G/EvData.lean (the q = 7 / q = 11 pattern tables, bnC, dC, pu/pv from RCert/G/Ev.lean).
# Usage: gen_lean_data.py SIG.json EVDATA.lean OUT.lean
import json, re, sys, hashlib

sig = json.load(open(sys.argv[1]))
ev = open(sys.argv[2], encoding="utf-8").read()

def arr(name):
    m = re.search(r"def " + name + r" : Array Nat := #\[([^\]]*)\]", ev, re.S)
    assert m, name
    return [int(t) for t in m.group(1).replace("\n", " ").split(",") if t.strip()]

def nat(name):
    m = re.search(r"def " + name + r" : Nat := (\d+)", ev)
    assert m, name
    return int(m.group(1))

w7, f7, q7, w11, f11, q11, bnC, dC = (arr(n) for n in ["w7", "f7", "q7", "w11", "f11", "q11", "bnC", "dC"])
np7, np11 = nat("np7"), nat("np11")
assert (np7, np11) == (19, 2) and len(dC) == 24 and len(bnC) == 96
pu = [0, 0, 0, 0, 1, 1, 1, 2, 2, 3]
pv = [0, 1, 2, 3, 1, 2, 3, 2, 3, 3]
npC = np7 * np11

# patterns as in Ev.lean: pwt, pf, pw (with the multiplicity m_k = 1 on the diagonal, 2 off it)
def pw(P, t, k):
    a, b = P // np11, P % np11
    u, v = pu[k], pv[k]
    F7 = f7[4 * a + u] * f7[4 * a + v]; G7 = q7[16 * a + 4 * u + v]
    F11 = f11[4 * b + u] * f11[4 * b + v]; G11 = q11[16 * b + 4 * u + v]
    m = 1 if u == v else 2
    return m * (F7 * F11 if t == 0 else G7 * F11 if t == 1 else F7 * G11 if t == 2 else G7 * G11)
pats = []
for P in range(npC):
    pats.append((w7[P // np11] * w11[P % np11], [f7[4 * (P // np11) + u] * f11[4 * (P % np11) + u] for u in range(4)],
                 [[pw(P, t, k) for k in range(10)] for t in range(4)]))

# signature records: wt, fwg (u-major, fw(u + 4 i)), c[k] = 9 products fw(a) fw(b) then 3 z-pair values w1(a, b)
zp = {tuple(p): i for i, p in enumerate(sig["zpairs"])}
def zpair_list(k):
    u, v = pu[k], pv[k]
    out = []
    for i in range(3):
        j = (u + i - v) % 3
        out.append((u + 4 * i, v + 4 * j))
    return out
for k in range(10):
    for (a, b) in zpair_list(k):
        assert (a - b) % 3 == 0 and a % 4 == pu[k] and b % 4 == pv[k]
recs = []
for s in range(sig["nsig"]):
    fw, w1 = sig["fw"][s], sig["w1"][s]
    fwg = [[fw[u + 4 * i] for i in range(3)] for u in range(4)]
    c = []
    for k in range(10):
        u, v = pu[k], pv[k]
        row = [fw[u + 4 * i] * fw[v + 4 * j] for i in range(3) for j in range(3)]
        row += [w1[zp[(a, b)]] for (a, b) in zpair_list(k)]
        c.append(row)
    recs.append((sig["wtF"][s], fwg, c))

# bn coefficient lists per tau: t_w = 0 -> (h, bnC[24 t + c]) with dC[c] = h | 120; t_w = 1 -> (h, bnC[24 t + c]) with dC[c] = 3 h, 9 | 3 h
H0 = [h for h in dC if 120 % h == 0]
H1 = [h for h in H0 if h % 3 == 0]
assert len(H0) == 16 and len(H1) == 8
bn0 = [[bnC[24 * t + dC.index(h)] for h in H0] for t in range(4)]
bn1 = [[bnC[24 * t + dC.index(3 * h)] for h in H1] for t in range(4)]
for h in H1: assert (3 * h) % 9 == 0 and 360 % (3 * h) == 0
# every divisor of 360 is used exactly once per tau: dC = H0 (9 does not divide) + 3 * H1 (9 divides)
assert sorted(H0 + [3 * h for h in H1]) == sorted(dC)
assert all((h % 9 != 0) for h in H0)

o41 = []
z41 = 0
for r in range(41):
    m = sum(1 << e for e in range(120) if pow(2, e, 41) == r)
    if m: o41.append((m, 1))
    else: z41 += 1
o41.append((0, z41))
assert len(o41) == 21 and sum(c for _, c in o41) == 41
def L(xs): return "[" + ", ".join(str(x) for x in xs) + "]"
def LL(xss): return "[" + ", ".join(L(x) for x in xss) + "]"
out = []
out.append("/-! Generated by gen/gen_lean_data.py from gen/sig_data_v1.json and RCert/G/EvData.lean.")
out.append(f"   sig json sha256 {hashlib.sha256(open(sys.argv[1], 'rb').read()).hexdigest()[:16]}, EvData sha256 {hashlib.sha256(ev.encode()).hexdigest()[:16]}. -/\n")
out.append("set_option maxRecDepth 100000\n")
out.append("namespace R45.GK\n")
out.append("/-- A signature of the fibered component (19, 73, 37): weight, `f_w(u + 4 i)` (u-major), and per pair k the 9 products")
out.append("`f_w(a) f_w(b)` (a = u_k + 4 i, b = v_k + 4 j) followed by the 3 values `W_w^1(a, b)` of the z-equal pairs. -/")
out.append("structure Sig where\n  wt : Nat\n  fwg : List (List Nat)\n  c : List (List Nat)\n")
out.append("/-- A pattern of the independent residues (23, 43, 29): weight, `F_P(u)`, `m_k W^tau_P(u_k, v_k)` per tau. -/")
out.append("structure Pat where\n  pw : Nat\n  pf : List Nat\n  pq : List (List Nat)\n")
out.append("/-- The divisors h | 120 with `bnC` coefficients: t_w = 0 (g_c = h), t_w = 1 (g_c = 3 h, 9 | g_c). -/")
out.append(f"def H0 : List Nat := {L(H0)}")
out.append(f"def H1 : List Nat := {L(H1)}")
out.append(f"def bn0 : List (List Nat) := {LL(bn0)}")
out.append(f"def bn1 : List (List Nat) := {LL(bn1)}\n")
out.append("/-- `optsP 120 41` as a literal (masks at period 120 with their counts). -/")
out.append("def o41r : List (Nat × Nat) := [" + ", ".join(f"({m}, {c})" for (m, c) in o41) + "]\n")
out.append("/-- The signature index of each option triple of (19, 73, 37), in the order o19 (outer), o73, o37 (inner). -/")
def chunked(name, typ, items, n, fmt):
    parts = [items[i:i + n] for i in range(0, len(items), n)]
    for i, part in enumerate(parts):
        out.append(f"def {name}_{i} : {typ} := [" + ", ".join(fmt(x) for x in part) + "]")
    out.append(f"def {name} : {typ} := " + " ++ ".join(f"{name}_{i}" for i in range(len(parts))) + "\n")
chunked("sigF", "List Nat", sig["sigF"], 500, str)
out.append("/-- The canonical signature tables: `f_w(a)` (a < 12) and `W_w^1(a, b)` on the 48 pairs a = b (mod 3), a-major. -/")
chunked("fwT", "List (List Nat)", sig["fw"], 100, L)
chunked("w1T", "List (List Nat)", sig["w1"], 50, L)
out.append("/-- The signature records (weights summed over the triples of each signature). -/")
chunked("sigs", "List Sig", recs, 25, lambda r: f"⟨{r[0]}, {LL(r[1])}, {LL(r[2])}⟩")
out.append("/-- The 38 patterns (np7 * np11), in the order of `P` of RCert/G/Ev.lean. -/")
out.append("def pats : List Pat := [")
out.append(",\n".join(f"  ⟨{w}, {L(pf)}, {LL(pq)}⟩" for (w, pf, pq) in pats) + "]\n")
out.append("end R45.GK")
txt = "\n".join(out) + "\n"
open(sys.argv[3], "w", encoding="utf-8").write(txt)
print("wrote", sys.argv[3], "sigs", len(recs), "pats", len(pats), "sha256", hashlib.sha256(txt.encode()).hexdigest()[:16])
